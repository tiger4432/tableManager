// S-19 «화면 절반» — 「이 원점이 «무엇 위에» 섰나」의 클라 한 자리.
//
// 🔴 이 라운드가 닫는 문장: **원점 상자가 유효 다이 마스크에서 웨이퍼 원으로 «물러났는데»
//    화면에 그 말을 할 칸이 없습니다.** 좌표는 그대로이고 오류도 안 납니다 — 운영자는
//    마스크 기준인 줄 압니다. 등급 2(「서버가 말하는데 듣는 쪽이 0」)이고, 서버 절반은
//    이미 닫혔습니다(`02f51b92`, `map_alignment.py` -> `maps[].origin_basis`).
//
// 🔴 왜 이 파일이 있나. `attestation.js` 와 «같은 사유»입니다 — 판정이 `main.js` 의
//    `renderSources` 클로저에 살면 채점하려고 DOM 을 통째로 세워야 합니다. 표준 규율은
//    「재려는 로직을 import 되는 모듈로 뺀다」입니다.
//
// ⛔ `attestation.js` 와 «합치지» 않습니다. 그쪽은 「사람이 이 프레임을 확정했나」이고
//    이쪽은 「원점 상자가 무엇 위에 섰나」입니다. 한 맵에서 «둘 다 참»일 수 있으므로
//    다른 질문이고, 한 판정으로 접으면 둘 중 하나가 조용히 사라집니다.
//
// ⛔ 「마스크 기준」이라고 «이름 대지» 않습니다 (총괄 판정 36) — 물러난 맵에 그 말을 붙이면
//    화면이 «거짓»을 말하고 이 줄이 등급 1 로 올라갑니다. 말하는 것은 그 «반대»입니다.

// 🔴 서버의 철자 그대로입니다 — `server/map_overlay.py:1217-1224` 가 정본이고, 저장
//    경로(S-22)도 «같은 넷»을 씁니다. 여기서 다시 철자하거나 클라 동의어를 만들면
//    그날부터 두 어휘가 «갈라질 수» 있고, 갈려도 오류가 안 납니다.
// ⚠️ 넷을 여기 «전부» 적는 이유는 값 하나만 아는 독자가 「나머지는 없다」로 읽기 때문입니다.
export const ORIGIN_BASIS_MASK = 'mask';                    // 마스크가 상자를 정했다 (의도대로)
export const ORIGIN_BASIS_CIRCLE = 'circle';                // 마스크가 «없어» 원이 정했다 (정상이고 흔하다)
export const ORIGIN_BASIS_MASK_OFF_GRID = 'mask_off_grid';  // 마스크는 «있는데» 이 격자 밖이라 원으로 «물러났다»
export const ORIGIN_BASIS_ABSENT = 'absent';                // 격자가 없어 «상자 자체»가 없다

// 🔴 넷 중 «하나»만 그립니다. 판별식은 UI 상설의 그것입니다 —
//    「이 문장을 지우면 운영자가 «틀리게» 읽나」.
//      mask     지운다 — 의도대로 섰다. 말할 것이 없다
//      circle   지운다 — «정상이고 흔하다». 그리면 대부분의 맵에 잡음이 붙는다
//      absent   지운다 — 격자가 없다는 사실은 그 맵의 «다른 자리»가 이미 말한다
//      🔴 mask_off_grid  «남긴다» — 마스크가 있는데 «안 쓰였다»
const NOTE = '원점 원(마스크 격자 밖)';

/**
 * 이 출처 행이 «원점»에 대해 무엇을 말해야 하나.
 *
 * @param {object} src  적응된 출처 행 — `origin_basis` «한 칸»만 읽습니다.
 * @returns {{basis: string|null, note: string}}  `note` 가 빈 문자열이면 «아무 말도 안 합니다».
 *
 * 🔴 `note` 가 이 라운드의 «전부»입니다. `basis` 는 그것이 «무엇에서» 나왔는지이고,
 *    둘이 한 반환값이라 «갈라질 수 없습니다».
 *
 * ⚠️ 칸이 «없으면» 뜻은 «하나»입니다 — 「옛 서버」. 서버는 상자를 못 만든 맵에도
 *    `absent` 를 실으므로(총괄 판정 48), 부재가 두 뜻이 될 수 없습니다. 그때는
 *    «안 그립니다» — 「0」도 「모름」도 지어내지 않습니다.
 */
export function originBoxNote(src) {
  const basis = src && src.origin_basis != null ? String(src.origin_basis) : null;
  // 🔴 «엄격히» 그 값일 때만. 모르는 값(넷 밖의 다섯째, 또는 옛/새 서버의 오타)은
  //    «안 그립니다» — 못 읽은 값에 문장을 붙이는 것이 조용히 틀리는 자리입니다.
  return { basis, note: basis === ORIGIN_BASIS_MASK_OFF_GRID ? NOTE : '' };
}
