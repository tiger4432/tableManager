// ═══════════════════════════════════════════════════════════════════════════════
// TRUNCATION — 「잘렸나」를 «상한과 돌아온 행»으로만 답하는 한 곳
//
// 🔴 `total` 을 «받지 않습니다». 받는 순간 이 파일을 쓰는 요청이 전수 count 를 다시
//    치러야 하고, 그것이 이 라운드가 없애려는 비용입니다 (카운트가 첫 화면의 66~95%).
//    상한+1 로 요청해서 «한 행 더 왔나»를 보면 `total` 과 «같은 정확도»입니다.
//
// 🔴 판별식은 «정확히 상한만큼» 왔을 때입니다. 상한으로 요청하고 `length >= cap` 으로 보면
//    딱 맞는 정상 응답을 «절단»으로 읽습니다 -- 그러면 온전한 맵이 「불완전」으로 강등되고,
//    화면은 있는 것을 없다고 말합니다. 그래서 상한«+1»로 묻고 `>` 로 봅니다.
// ═══════════════════════════════════════════════════════════════════════════════

/** 상한+1 로 요청할 때 쓸 `limit`. 「하나 더 왔나」를 볼 수 있게 «한 행»만 더 청합니다. */
export function fetchLimitFor(cap) {
  return cap + 1;
}

/** 잘렸나. `rows` 는 «돌아온 그대로»여야 합니다 (자르기 «전»). */
export function isTruncated(rows, cap) {
  if (!Number.isFinite(cap) || cap < 0) return false;
  return (Array.isArray(rows) ? rows.length : 0) > cap;
}

/** 상한까지만. 상한+1 로 청했으므로 그 «한 행»은 신호이지 데이터가 아닙니다 --
 *  안 자르면 화면이 상한을 «하나 넘겨» 그립니다. */
export function withinCap(rows, cap) {
  if (!Array.isArray(rows)) return [];
  if (!Number.isFinite(cap) || cap < 0) return rows;
  return rows.length > cap ? rows.slice(0, cap) : rows;
}

// ═══════════════════════════════════════════════════════════════════════════════
// 🔴 「이 응답이 «잘렸다»고 말하나」 — 전선의 «모양»을 아는 한 곳
//
// 위의 셋은 「돌아온 행이 상한을 넘었나」를 «클라가» 판정합니다. 이것은 다른 질문입니다 --
// «서버가 자기 응답에 대해 뭐라 하는가». 두 질문이 한 파일에 있는 이유는 운영자에게는
// 「잘렸다」가 하나이기 때문이고, 그래서 답도 한 자리에 있어야 합니다.
//
// 🔴 «항상 오는» 칸의 있음·진릿값에는 뜻이 없습니다. 물을 것은 「참인가」입니다.
//    실측 2026-09-06: 전선의 `truncated` 가 «다섯 모양»입니다 -- 불리언 · 이름이 다른
//    불리언 둘 · 축 객체(«항상» 온다) · 레코드 배열(«잘렸을 때만» 온다). 그리고 축 객체는
//    안 잘려도 옵니다. `reason` 만 null 입니다. 그래서 `if (truncated)` 로 읽으면
//    «매번» 「절단됨」이 뜹니다 (`rnd_board/api.js` 가 그 함정을 이미 적어 뒀습니다).
//
// 🔴 그러므로 진릿값이 아니라 «사유»를 봅니다. 축이 하나라도 참일 때에만 서버가 사유를
//    싣고, 아무것도 안 잘렸으면 null 입니다 -- 그 둘은 «같은 사실»이라 사유 하나로 족합니다.
//
// ⚠️ 모르는 모양은 «거짓이 아니라 모름»입니다. 없는 칸을 false 로 접으면 「안 잘렸다」와
//    「이 서버는 말해 주지 않는다」가 한 답이 됩니다. 부르는 쪽은 `=== true` 로 씁니다.
//
// 🔴 소속은 «수»가 아니라 «판별식»입니다:
//        「서버 «응답 본문»의 `truncated` 를 읽나」
//    ✅ 오늘 지나는 곳 — 넷, 모듈 셋
//         value_suggest.js  `body.truncated`   (값 제안 라우트)
//         map_editor.js     `body.truncated`   (🔴 «같은 라우트»를 각자 읽던 둘째 자리)
//         timeline.js       `body.truncated`   × 2 (`/audit_logs/recent` · `/history`)
//    ✅ 그 후보 둘이 «들어왔습니다** (S-5, 2026-09-07). 소속 판별식이 서 있었으므로 이것은
//       «확장»이지 누락 수리가 아닙니다 — 그리고 둘 다 자기 `=== true` 를 쓰고 있었는데,
//       그 형태는 «불리언 모양»만 읽어 객체 `{reason}` 을 「안 잘림」으로 떨어뜨렸습니다
//         map2/decode.js   payload 의 `sources.truncated`
//         map2/api.js      참조 카탈로그 «봉투»의 `truncated`
//    🔴 판별식이 서 있으므로, 둘이 나중에 들어오는 것은 «확장»이지 «누락 수리»가 아닙니다.
//       그래서 이 파일이 `client2/src/` 에 있습니다 — map2 가 `../truncation.js` 로 «부를 수
//       있는» 자리입니다. 지금 안 부르는 비용은 0 이고, 나중에 «못» 부르면 그것이 사본을
//       만드는 유혹이 됩니다.
//
// 🔴 그리고 이 한 자리의 값어치는 「코드가 준다」가 아니라 «둘이 같은 답을 받는다»입니다.
//    `value_suggest` 와 `map_editor` 는 «같은 라우트»의 같은 칸을 각자 읽고 «다른 문장»을
//    만듭니다(하나는 캐시 판단, 하나는 화면 문구). 갈라져도 «오류가 안 납니다» —
//    그래서 하니스가 「같은 본문 -> 같은 판정」을 단언합니다.
// ═══════════════════════════════════════════════════════════════════════════════

// ═══════════════════════════════════════════════════════════════════════════════
// 🔴 그리고 그 「다른 문장」을 «하나»로 접습니다 (클라 7 ㉯ · 판정 84).
//
// 바로 위 문단이 이름 댄 잔여가 이것입니다 — 값 제안이 잘렸다는 «같은 사실»을 두 화면이
// «다른 두 문장»으로 말하고 있었습니다. 같은 라우트, 같은 칸, 두 저자:
//     value_suggest.js  「상위 N개만 표시 — 더 입력하면 좁혀집니다」
//     map_editor.js     「값이 많아 앞의 N개만 내려왔습니다 — 더 입력하면 다시 좁혀 가져옵니다.」
// 오늘 «틀린 답은 아닙니다**(등급 6). 다만 한쪽만 고쳐지는 날 두 화면이 같은 상태를
// 다르게 설명하고, 그것은 오류를 «안 냅니다».
//
// ⛔ 문장을 «줄이지» 않았습니다 — 「더 입력하면 좁혀집니다」가 «다음 행동»이고, 그것을
//    떼면 「자막 단 실패」가 됩니다. 짧은 쪽을 골랐을 뿐입니다(UI 상설: 간결·명료).
// ⚠️ 이 파일에 «문구»가 사는 이유: 이 사실의 «판정»이 여기 살고, 문구가 다른 곳에 살면
//    다음 사람이 판정만 옮기고 문구를 두고 갑니다. 둘은 같은 사실의 두 면입니다.
// ═══════════════════════════════════════════════════════════════════════════════

/** 값 제안 목록이 잘렸을 때 «두 화면이 같이» 쓰는 한 문장. `shown` 은 «화면에 있는 수»입니다. */
export function suggestTruncatedNote(shown) {
  return `상위 ${shown}개만 표시 — 더 입력하면 좁혀집니다`;
}

// ═══════════════════════════════════════════════════════════════════════════════
// 🔴 여섯째 모양 — «정본 축-지도». 그리고 이것을 모르는 동안 이 함수는 «거짓»을 답했습니다.
//
//     truncated: { <축>: { cut, omitted, reason } }        (`event_constants.truncated_note`)
//
// 이 모양에는 «최상위 `reason` 이 없습니다». 그래서 아래의 `Boolean(said.reason)` 은
// «잘린 응답»에 대해 `false` 를 돌려줍니다 — 「모른다」도 아니고 «틀린 답»입니다.
// 화면은 잘린 목록을 «온전한 것»으로 그립니다. 오류 0.
//
// 🔴 판별은 `cut` 이지 `reason` 이 아닙니다. 서버는 `reason` 을 «잘렸고 사유가 있을 때만»
//    싣습니다(`truncated_note` 는 `reason if (reason and cut) else None`) — 사유 없이 잘리는
//    자리가 실재하므로(예산 비트만 아는 호출자) `reason` 으로 읽으면 그것을 «안 잘림»으로
//    떨어뜨립니다. 서버가 «판정»으로 쓰는 칸을 그대로 읽습니다.
//
// ⚠️ 앞의 다섯 모양은 «한 바이트도» 안 바뀝니다. 옛 subgraph 모양의 축은 «불리언»이고
//    (`{depth: true, nodes: false, reason: 'nodes'}`), 축-지도의 축은 «객체»입니다.
//    그래서 「값이 객체이고 `cut` 키를 가진 것이 하나라도 있나」가 둘을 가릅니다.
// ═══════════════════════════════════════════════════════════════════════════════

/** 응답이 「잘렸다」고 말하나. `true` · `false` · `null`(모름) 셋입니다. */
export function saysTruncated(said) {
  if (typeof said === 'boolean') return said;
  if (said && typeof said === 'object' && !Array.isArray(said)) {
    const axes = Object.values(said).filter(
      v => v && typeof v === 'object' && !Array.isArray(v) && 'cut' in v);
    if (axes.length) return axes.some(a => a.cut === true);
    return Boolean(said.reason);
  }
  return null;
}
