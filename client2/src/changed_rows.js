// ═══════════════════════════════════════════════════════════════════════════════
// 「이 푸시가 «몇 행을» 바꿨나」 — 수 하나와 그 수의 낱말.
//
// 🔴 판정 192 로 서버의 `updated_count` 가 「이 요청이 «바꾸거나 만든» 행 수」가 됐습니다.
//    안 바뀐 행은 응답에 «항목이 아예 없습니다». 그래서 «완전 무변경» 푸시의 정답은 «0»
//    이고, 0 은 «답»이지 부재가 아닙니다.
//
// ⛔ `a || b || c` 로 고르지 «않습니다». JavaScript 에서 0 은 falsy 라, 그 사슬은 맞는 답인
//    0 을 «버리고» 폴백으로 흘러갑니다 — 아무것도 안 바뀐 푸시가 «보낸 행 수»를 그대로
//    「200건」이라 말합니다. 이건 「없어서 0」과 「세어 보니 0」을 같은 픽셀로 만드는 부류의
//    «더 나쁜» 판입니다: 0 이 빈 칸이 되는 게 아니라 «지어낸 수»가 됩니다.
//
// 🔴 이 수를 쓰는 자리가 «둘»입니다 — 성공 토스트와 「규격 저장 실패」 토스트. 각자 고르면
//    한쪽만 고쳐지는 날 두 토스트가 «다른 수»를 말합니다. 기준 ④: 둘이 «갈라질 수» 없어야
//    하므로 한 함수를 지납니다.
//
// ⚠️ 천단위 구분을 «넣지 않습니다». 오늘 화면이 안 넣고 있고, 넣으면 이 수리의 변경 범위가
//    「0 인 경우」를 넘어섭니다 — 0 이 아닌 수의 픽셀은 이 파일 전후로 «같습니다».
// ═══════════════════════════════════════════════════════════════════════════════

import { ABSENT, isCount } from './absent.js';

/** 0 일 때의 낱말. 「0건」이 아니라 «무슨 일이 있었는지»를 말합니다. */
export const NOTHING_CHANGED = '바뀐 것 없음';

/**
 * 응답에서 「바뀐 행 수」를 골라 «화면 낱말»로.
 *
 * @param {object|null} result   쓰기 응답 (`updated_count` · 폴백 `count`)
 * @param {number} sentCount     둘 다 없을 때의 폴백 — «보낸» 행 수
 * @returns {string} `'235건'` · `'바뀐 것 없음'` · `'—'`
 */
export function changedRowsText(result, sentCount) {
  const r = result && typeof result === 'object' ? result : {};
  // 🔴 순서가 아니라 «숫자인가»로 고릅니다. 앞의 것이 «숫자면» 0 이어도 그것이 답입니다.
  const count = isCount(r.updated_count) ? Number(r.updated_count)
    : isCount(r.count) ? Number(r.count)
      : isCount(sentCount) ? Number(sentCount)
        : null;
  // ⚠️ 셋 다 수가 아닌 것은 «오늘 전선이 안 내는» 모양입니다 — 부르는 쪽이 배열 길이를
  //    넘기므로 폴백은 늘 수입니다. 그래도 수를 «지어내지» 않습니다: 못 얻은 수는 `—` 이고,
  //    0 이 아닙니다.
  if (count === null) return ABSENT;
  return count === 0 ? NOTHING_CHANGED : `${count}건`;
}
