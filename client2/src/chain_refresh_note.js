// C-9 — 「체인이 «몇 행» 냈나」. `batch_refresh_required` 가 도착했을 때의 한 줄.
//
// 🔴 왜 이 갈래인가 (판정 78 의 «한 측정»). 형제 갈래들은 «무엇이 바뀌었는지»를 보여 줍니다 —
//    `batch_row_upsert` 는 `flashCells` + `redrawRows` 로 칸을 깜빡이고 상태줄에 「N rows
//    updated」를 씁니다(`websocket.js`). 🔴 `batch_refresh_required` 갈래는 «둘 다 안 합니다**:
//    `pageCache.clear()` 와 이력 재적재뿐이라, 운영자에게는 «아무 일도 안 일어난 것»과 같습니다.
//    그래서 그 자리에서 수를 «말할» 자리가 비어 있고, 서버는 그 수를 «항상» 보내고 있었습니다.
//
// ⛔ 「바꿈」이라 쓰지 «않습니다**. C-9 의 사실은 「쓴 행 수」이지 「무언가가 달라졌다」가
//    아닙니다 — C-1 에서 `ran:changed` 에 대해 같은 이유로 같은 결정을 했습니다.
// ⛔ 새 영역·토스트·모달을 «만들지 않습니다** — 형제 셋이 이미 쓰는 «그 상태줄»입니다.
//
// ⚠️ 이 `change_count` 는 «웹소켓» 것입니다. 같은 이름이 «HTTP 저장 응답»에도 있고 그쪽은
//    독자가 넷입니다 — 한 이름 두 나르개라, 「독자 0」은 «이쪽»에서만 참입니다.

/**
 * `batch_refresh_required` 메시지가 상태줄에 쓸 한 줄.
 *
 * @param {object|null} msg  웹소켓 메시지
 * @returns {string}  빈 문자열이면 «아무것도 안 씁니다**
 *
 * 🔴 `0` 은 «값»입니다 — 「스윕 복구」가 그 수로 옵니다(서버가 자기 상수 옆에 그렇게 적어
 *    두었습니다). 「0 행」과 「이 서버는 그 말을 안 한다」는 다른 사실이고, 뒤엣것만 «침묵»입니다.
 */
export function chainRefreshNote(msg) {
  if (!msg || typeof msg !== 'object') return '';
  const n = msg.change_count;
  // 🔴 «수»일 때만. 문자열 `"3"` 은 서버가 낸 적 없는 모양이고, 강제로 수로 만들면
  //    계약이 조용히 넓어집니다 — 그다음 사람은 그 강제를 계약으로 읽습니다.
  if (!Number.isFinite(n)) return '';
  // 형제 갈래들이 쓰는 «그 슬롯»의 모양(기호 + 사실 + 수)을 그대로 따릅니다.
  return `⚡ 체인 ${n}행`;
}
