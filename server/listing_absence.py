"""목록 라우트가 «자기 원천이 없을 때» 내는 답 — 한 자리.

🔴 `absent` 는 `empty` 가 «아니다». 없는 디렉터리와 «있는데 빈» 디렉터리가 똑같이
`data: []` 를 내면, 부르는 쪽은 「설치가 덜 됐다」와 「아직 아무것도 없다」를 «구별할 수
없다». 실측 2026-09-07: 그 줄을 «손으로 쓴» 목록 라우트가 «넷»이고, 그중 «하나»가 이미
다른 셋에 없는 필드를 달고 있었다 — 판형에 집이 없으면 그렇게 갈라진다.

낱말은 «새로 짓지 않았다**. `ledger_trace.COVERAGE_STATES` 가 이미 쓰는 것을 그대로 쓴다:
`absent` = 답을 담을 것이 «없다» · `empty` = 있는데 «비었다».

⚠️ **더하기만 한다.** `status` 는 `success` 로 «둔다» — 실패한 것은 «요청»이 아니기
때문이다. `data` 만 보는 독자는 «전과 똑같이» 돌고, 「없음」과 「빔」을 가르려는 독자에게만
`state` 와 «어느 경로인지»가 생긴다. 그래서 이 변경에 회귀 반경이 «없다».
"""

#: `ledger_trace.COVERAGE_STATES` 의 낱말. 여기서 «다시 정의하지 않는다** —
#: 같은 뜻에 두 철자가 생기면 화면이 둘 중 하나만 알게 된다.
LISTING_ABSENT = "absent"


def absent_listing(path, **extra):
    """원천 경로가 «없는» 목록의 답.

    `path` 는 «찾다가 못 찾은 그 경로»다. 운영자가 고칠 자리를 그 문자열로 찾으므로
    이름을 «지우지 않는다** — 「목록이 비었다」만 남으면 어디를 볼지가 사라진다.

    `extra` 는 «그 라우트만의» 칸이다. 넷 중 하나가 `last_updated` 를 싣는데, 그것은
    그 라우트의 개념이지 «부재»의 개념이 아니라 공용 모양에 «안 넣는다** —
    넷 다 싣게 하면 나머지 셋에 뜻 없는 칸이 생긴다.
    """
    answer = {"status": "success", "data": [],
              "state": LISTING_ABSENT, "absent_path": str(path)}
    answer.update(extra)
    return answer
