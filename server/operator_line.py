# -*- coding: utf-8 -*-
"""운영자가 읽는 «한 줄» — 무엇이 일어났나, 그리고 «다음에 무엇을 하나» (S-247).

> 소유자 2026-09-15: 「난 이 에러를 **이해할 수가 없다, 조치를 뭘 해야 하는지 안 알려줌**」
> 같은 날: 「**운영은 보안 땜에 못 붙여**」

🔴 그 두 문장이 «같은 요구»입니다. 운영 로그는 밖으로 나올 수 없으므로 — 붙여 넣고 물어볼
   수가 없으므로 — **줄이 «혼자» 답해야 합니다.** 무엇이 일어났는지만 말하는 줄은, 그것을
   읽을 사람이 뒤에 더 물을 수 있을 때만 완성된 줄입니다. 여기서는 물을 수가 없습니다.

⛔ 그리고 «조치 없는 줄»은 중립이 아닙니다. 이 제품에는 **같은 증상에 수리가 «정반대»인**
   자리가 있습니다:

       조인 키가 «신원보다 좁다»   -> 고칠 것은 «선언»이다 (데이터를 접으면 사실이 사라진다)
       진짜 중복이다               -> 고칠 것은 «데이터»다 (선언을 넓히면 중복이 남는다)

   둘이 «같은 낱말»(중복 키)로 로그에 나오므로, 조치를 안 실은 줄은 운영자를 반반의 확률로
   «틀린 수리»로 보냅니다. 그것이 이 모듈이 있는 이유이고, 그래서 다음 행동의 문장은
   부르는 자리가 «지어내지» 않고 여기 있는 것 중에서 «고릅니다».

⚠️ 이 모듈은 stdlib 말고 아무것도 import 하지 않습니다 — `virtual_join/refusal.py` 와 같은
   자세입니다. 네 자리가 서로 다른 패키지(`chain` · `database` · `virtual_join`)에 살고,
   그중 어느 쪽도 나머지를 읽지 않아야 합니다.

📎 `virtual_join/refusal.py` 와 «다른 것»입니다. 그쪽은 «화면»이 읽는 문장(설정 보고서와
   verify 라우트)의 정본이고, 이쪽은 «로그»가 읽는 줄의 정본입니다. 화면에는 저자가 있었고
   로그에는 없었습니다 — 그런데 운영에 실제로 있는 채널은 로그 쪽입니다.
"""

#: 표본은 셋까지. 넷째부터는 세는 것이 답이지 나열하는 것이 답이 아니고, 수천 건짜리
#: 나열은 진단이 아니라 덤프입니다.
MAX_SAMPLES = 3


# --- 다음 행동 «닫힌» 어휘 -------------------------------------------------
# 🔴 함수인 이유: 행동마다 «채워야 할 이름»이 다릅니다. 문자열 상수로 두면 부르는 자리가
#    포맷을 짜게 되고, 그 순간 저자가 넷이 됩니다. 새 행동이 필요하면 여기 함수를 하나
#    더합니다 — 그러면 그 행동이 «무엇을 말해야 하는지»가 한 자리에서 정해집니다.

def fold_the_data(table: str, columns) -> str:
    """진짜 중복이다 — 그 표의 행을 합쳐라."""
    return ("%s 에서 그 키(%s)의 행들을 «하나로 합치십시오». 합쳐도 되는지는 접기 계획이 "
            "가릅니다(RUN.md §2)" % (table, _names(columns)))


def widen_the_key(where_declared: str, what_to_add: str) -> str:
    """키가 신원보다 좁다 — 선언을 넓혀라. 데이터는 «건드리지 마라»."""
    return ("%s 에 %s 을(를) 더 적으십시오 — 이 키로는 그 표의 행이 «구별되지 않습니다». "
            "데이터를 합치면 사실이 사라집니다" % (where_declared, what_to_add))


def fill_or_declare_null(table: str, columns) -> str:
    """키가 «비어 있다» — 중복이 아니라 부재다."""
    return ("%s 의 %s 를 채우거나, 카탈로그에 그 컬럼의 null 정책(`null_policy`)을 "
            "적으십시오" % (table, _names(columns)))


def rename_one_declaration(files) -> str:
    """같은 이름이 «두 선언»에 있다 — 한쪽 이름을 바꿔라. 어느 쪽인지는 제품이 못 고른다 (S-234 ①).

    `files` 는 그 이름이 적힌 파일들. 서로 다른 파일이 둘이면 판정 409 의 문장 그대로이고,
    한 파일 안에서 두 번이면 그 파일을 가리킨다.
    """
    distinct = sorted(set(str(item) for item in (files or ())))
    if len(distinct) > 1:
        return "두 파일 중 하나에서 이름을 바꾸십시오"
    return "%s 에서 한쪽 선언의 이름을 바꾸십시오" % (_names(distinct) or "그 파일")


def retract_the_declaration(where_declared: str) -> str:
    """제품이 «세운» 인덱스를 어겼다 — 선언을 끄면 제품이 «스스로» 걷는다 (S-248, S-269).

    🔴 손으로 `DROP INDEX` 를 하면 다음 재기동이 «다시 세웁니다». 인덱스의 수명은 그것을
       요구하는 조인 선언의 수명과 «같고», 그 문장이 이 항목의 전부입니다.
    """
    return ("%s 를 끄거나 지우십시오 — 그 인덱스는 제품이 «그 선언 때문에» 세운 것이라, "
            "선언이 없어지면 제품이 «스스로» 걷습니다. 손으로 DROP INDEX 하지 마십시오"
            % where_declared)


def decide_the_repair(table: str, constraint: str) -> str:
    """제약을 어겼는데 «어느 수리인지 제품이 모른다» — 두 수리가 정반대다 (S-269).

    ⚠️ 여기서 하나를 고르면 «틀릴 때 사실이 사라집니다». 진짜 중복이면 데이터를 접고,
       키가 신원보다 좁으면 선언을 넓힙니다 — 뒤집으면 못 되돌립니다. 그래서 이 행동은
       「가르십시오」이고, 가르는 법이 적힌 자리를 댑니다.
    """
    return ("%s 의 제약 `%s` 가 무엇을 막는지 보고 «수리를 가르십시오» — 진짜 중복이면 "
            "데이터를 접고, 키가 좁으면 선언을 넓힙니다(정반대입니다). 가르는 법은 "
            "RUN.md §2 에 있습니다" % (table, constraint))


def restart_to_clear_the_pool() -> str:
    """빌린 연결이 «트랜잭션을 못 여는» 상태다 — 운영자가 할 수 있는 것은 풀을 비우는 것뿐 (S-271).

    ⚠️ 「데이터를 고치라」도 「선언을 고치라」도 아니다. 오염은 «연결 하나»에 붙어 그것이 풀에서
       밀려날 때까지만 산다 — 그래서 다음 요청은 멀쩡할 수 있고, «반복»되는 것이 신호다.
    """
    return ("이 연결이 트랜잭션을 못 여는 상태로 풀에 있습니다 — 다음 요청은 다른 연결을 받을 "
            "수 있습니다. 같은 줄이 «반복»되면 재기동이 풀을 비웁니다")


def restart_to_apply() -> str:
    """제품이 알아서 할 일이 남아 있다 — 한 번 재기동."""
    return "재기동하면 제품이 «스스로» 세웁니다. 손으로 DDL 을 돌릴 일은 없습니다"


def nothing_to_do(unless: str = "") -> str:
    """⚠️ 「없음」도 «행동»입니다. 이 줄을 보고 아무것도 안 해도 된다는 것을 모르면,
    운영자는 무엇이든 합니다.

    🔴 [S-247-b] 첫 판은 이 문장에 「건너뛴 것을 셉니다」를 «박아» 두었고, 그래서 부르는
    자리가 «하나도» 없었습니다 — 읽는 쪽 없는 칸을 제가 또 만든 것입니다. 지금은 어느
    자리에서나 참인 것만 말하고, 그 자리에만 참인 조건은 `unless` 로 받습니다.
    """
    return ("없음 — 이 줄은 «알림»이고 지금 조치할 것이 없습니다"
            + (" (%s)" % unless if unless else ""))


def _names(seq) -> str:
    """이름 목록을 문장에 넣을 수 있는 형태로. `['slot']` 이라는 repr 이 운영자에게
    가면 대괄호부터 해독해야 문장을 읽을 수 있습니다."""
    if isinstance(seq, str):
        return seq
    return ", ".join(str(item) for item in (seq or ()))


def samples_of(items, cap: int = MAX_SAMPLES) -> str:
    """표본 ≤3 과 «전체 수». 셋만 보이고 수를 안 말하면 「셋뿐」으로 읽힙니다."""
    items = list(items or ())
    if not items:
        return ""
    shown = ", ".join(str(item) for item in items[:cap])
    return shown + (" 외 %d" % (len(items) - cap) if len(items) > cap else "")


def line(where: str, subject: str, what: str, action: str, samples=()) -> str:
    """운영자 한 줄. 「다음:」 절이 «없는» 줄은 이 함수가 만들 수 없습니다.

    `where`   어느 자리가 말하는가 (`VirtualJoinUnique` · `join_into` …)
    `subject` 그 자리가 다루던 «규칙 이름», 없으면 «표 이름» — 운영자가 찾아갈 대상
    `what`    무엇이 일어났나. 수와 키를 담는다
    `action`  다음에 무엇을 하나. 위 어휘 중 하나 — 부르는 자리가 짓지 않는다
    `samples` 표본 ≤3 (행 이름·키)

    ⚠️ 접두 대괄호는 «검색어»입니다. 운영자가 로그에서 이 줄을 찾는 방법이 그것 하나이고,
    자리마다 다른 모양이면 찾을 수 없습니다.
    """
    body = "[%s:%s] %s" % (where, subject, what)
    shown = samples_of(samples)
    if shown:
        body += " (표본: %s)" % shown
    return "%s → 다음: %s" % (body, action)
